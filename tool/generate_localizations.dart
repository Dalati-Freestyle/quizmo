import 'dart:convert';
import 'dart:io';

Future<void> main() async {
  final catalogs = <String, Map<String, dynamic>>{};
  for (final language in ['en', 'de']) {
    final decoded = jsonDecode(
      await File('lib/presentation/l10n/$language.json').readAsString(),
    );
    if (decoded is! Map<String, dynamic> ||
        decoded.values.any((value) => value is! String)) {
      throw FormatException(
        'The $language catalog must contain string values only.',
      );
    }
    catalogs[language] = decoded;
  }
  final english = catalogs['en']!;
  final german = catalogs['de']!;
  if (english.length != german.length ||
      english.keys.any((key) => !german.containsKey(key))) {
    throw const FormatException(
      'The English and German catalogs must have identical keys.',
    );
  }
  Set<String> placeholders(String value) =>
      RegExp(r'\{\d+\}')
          .allMatches(value)
          .map((match) => match.group(0)!)
          .toSet();
  for (final key in english.keys) {
    final expected = placeholders(key);
    for (final catalog in catalogs.values) {
      final actual = placeholders(catalog[key] as String);
      if (actual.length != expected.length || !actual.containsAll(expected)) {
        throw FormatException('Placeholder mismatch for "$key".');
      }
    }
  }
  String quote(String text) => jsonEncode(text).replaceAll(r'$', r'\$');
  final output = StringBuffer(
    '// Generated by dart run tool/generate_localizations.dart.\n',
  );
  for (final entry in catalogs.entries) {
    output.writeln(
      'const ${entry.key == "de" ? "german" : "english"}Messages = <String, String>{',
    );
    for (final key in entry.value.keys.toList()..sort()) {
      output.writeln('  ${quote(key)}: ${quote(entry.value[key] as String)},');
    }
    output.writeln('};');
  }
  await File('lib/presentation/l10n/translations.g.dart')
      .writeAsString(output.toString());
  stdout.writeln('Generated ${english.length} messages in two languages.');
}
